/**
 * service-faqs.ts — 服務頁 FAQ 單一來源（Single Source of Truth）
 *
 * 為何要有這個檔案（2026-09-21 服務頁審計，deliverables/22）：
 *
 *   問題：FAQ 的「結構化資料（schema）」與「頁面可見內容」一向分開維護：
 *         · schema 寫在各服務的 page.tsx（硬編碼或陣列）
 *         · 可見內容寫在各服務的 ServiceContent 元件
 *         兩邊各自修改，就會出現不一致。
 *
 *   實例：AI 頁的 schema（ai 的 page.tsx 內 aiFaqs）與畫面（AiServiceContent.tsx
 *         的 faqItems）是兩份完全不同的問題清單 —— 連問題本身都唔一樣。
 *         這會令 Google 收到與頁面內容不符的 FAQ 標記，屬結構化資料違規風險。
 *
 *   另外三個頁面（服務總覽、流程自動化、商業攝影製作）
 *   有可見 FAQ 但完全沒有 schema，白白失去 rich result 機會。
 *
 *   做法：所有 FAQ 內容集中在這裡，page.tsx（出 schema）與 Content 元件（出畫面）
 *         都由這裡 import。任何一方改動，另一方自動同步，不可能再出現不一致。
 *
 * 使用方式：
 *   page.tsx          → import { AI_FAQS } from '@/lib/service-faqs'
 *                       <FAQJsonLd faqs={AI_FAQS} />
 *   *ServiceContent   → import { AI_FAQS } from '@/lib/service-faqs'
 *                       {AI_FAQS.map((f) => ...)}
 *
 * ⚠️ 修改須知：FAQ 文字會同時出現在頁面及 Google 的結構化資料中，
 *    因此內容必須與頁面其他部分一致，且不可包含未經核實的成效保證。
 */

